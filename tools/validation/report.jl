# report.jl — writes tools/validation/REPORT.md, the cross-check summary
# (agreement per reference × estimator, and every documented difference).
#
#   julia --project=. tools/validation/report.jl [out.md]
#
# Reads the same rows the test group asserts (test/validation/CrossCheck.jl).
using SigmaTau, Printf

include(joinpath(@__DIR__, "..", "..", "test", "validation", "CrossCheck.jl"))
using .CrossCheck: Row, relerr, passes, all_rows

const OUT = length(ARGS) >= 1 ? ARGS[1] : joinpath(@__DIR__, "REPORT.md")

const NOTES = """

## Conventions of the rows

- **Bias correction.** allantools returns the total deviations and Thêo1
  uncorrected, so its rows call `totdev`, `mtotdev`, `ttotdev`, `htotdev`
  and `theo1` with `correct_bias=false`. Stable32 corrects the total and
  the Hadamard total deviation on FM noise and prints the modified total
  and time total deviations uncorrected. Its total and Hadamard total rows
  take the uncorrected value of this package with Stable32's factor for the
  noise type Stable32 printed, so that they compare the estimator and not
  the noise identification. Its modified total and time total rows use
  `correct_bias=false`.
- **Noise type.** The Stable32 rows of the Hadamard deviations use
  `remove_drift=false`, which identifies the noise on the record as given,
  as Stable32 does. The rows "Stable32 CI (S32 α)" compute the interval for
  the noise type Stable32 printed, which separates the EDF model from the
  noise identification.
- **Thêo1 averaging time.** allantools reports Thêo1 at τ = m·τ0, this
  package and Stable32 at τ = 0.75·m·τ0. Rows are matched on m.
- **Thêo1 bias.** The `theobr` rows compare the Thêo1 run that Stable32
  makes with automatic noise identification, which removes the bias, with
  `theo1` under `correct_bias=:stable32`. The `theo1` rows compare its runs
  made for white FM, where the bias factor is 1, with `correct_bias=false`.
- **Welch spectra.** The rows compare `psd_y` with `scipy.signal.welch`
  from the second bin above zero. In the bins below it scipy removes the
  plain mean of each segment and this package the taper-weighted mean.
  `psd_x` is `psd_y` divided by the response of the first difference and
  has no rows of its own.
- **Record length in the EDF of the total deviations.** SP1065 Tables 7
  and 8 give edf = b·T/τ − c. allantools takes T/τ = N/m and this package
  (N − 1)/m, a relative difference of 1/N. The EDF rows compare the formula
  at the T of allantools.
- **Time total deviation.** In allantools it is the modified total
  deviation times τ/√3, so the generator derives it from that run.
- **MTIE.** The rows compare allantools' `mtie`. Stable32's "MTIE (Fast)"
  agrees within 4e-5 at each τ it reports.
- **1000-point test suite** (SP1065 §12.4). The overlapping Allan, modified
  Allan, time, overlapping Hadamard, total and Hadamard total values are
  those of Table 31. Its Hadamard total values carry the white FM factor
  (B = 0.995) above m = 1. For the modified total and time total deviations
  Table 31 lists corrected values, the uncorrected ones divided by √0.73.
  Their rows compare the uncorrected values of Stable32 1.60, and the Thêo1
  rows Stable32's uncorrected Thêo1, as the allantools test for this record
  gives them. The parabolic deviation values are from the same test,
  computed there with the `PDev` program of SigmaTheta 3.0 (October 2023).

## Not compared

- `mhdev`, `htdev`, `mhtotdev` and `ncornered_hat`: none of the programs
  above computes them. They are tested in `test/stab/` against direct
  evaluation of their definitions and against identities.
- ThêoH, and ThêoBR under `correct_bias=:published`. No program above
  measures the bias ratio up to a tenth of the record (n = ⌊N/30 − 3⌋,
  Howe 2006, Eq. (6)). By default this package measures it up to half the
  record (n = ⌊N/6 − 3⌋, SP1065 Eq. (33)), as Stable32 does. The two
  ratios, in variance, are 1.086 and 0.602 on the test suite, a white FM
  record, and 0.355 and 2.05 on the 8192-point record, where PM noise
  gives way to FM noise. Stable32's values are compared with
  `correct_bias=:stable32`, which takes its ratio from at most 3000 points
  as Stable32 does: the `theobr` rows above, and in
  `test/stab/stable32gen.jl` the two Thêo1 points of its ThêoH run on the
  8192-point record, which the default matches within 2 %.
"""

e(x) = isnan(x) ? "–" : x == 0 ? "0" : @sprintf("%.1e", x)

function main()
    rows = all_rows()
    io = IOBuffer()
    println(io, "# Reference cross-check report\n")
    println(io, "Generated by `tools/validation/report.jl` from the rows that ",
                "`test/validation/runtests.jl` asserts. Relative error is ",
                "|SigmaTau − reference| / |reference| (Welch spectra: relative to the spectral peak).\n")
    asserted = filter(r -> isfinite(r.tol), rows)
    println(io, "$(length(rows)) comparisons, $(length(asserted)) asserted, ",
                "$(count(!passes, rows)) failing.\n")

    println(io, "## Agreement\n")
    println(io, "| Reference | Estimator | Rows | Worst rel. error | Tolerance |")
    println(io, "|---|---|---:|---:|---:|")
    keyf(r) = (r.group, replace(r.estimator, r" (lo|hi)$" => ""))
    groups = Dict{Tuple{String,String},Vector{Row}}()
    order = Tuple{String,String}[]
    for r in asserted
        k = keyf(r)
        haskey(groups, k) || push!(order, k)
        push!(get!(groups, k, Row[]), r)
    end
    for k in order
        rs = groups[k]
        fin = filter(r -> isfinite(r.ref) && isfinite(r.got), rs)
        worst = isempty(fin) ? NaN : maximum(relerr, fin)
        println(io, "| $(k[1]) | $(k[2]) | $(length(rs)) | $(e(worst)) | $(e(maximum(r.tol for r in rs))) |")
    end

    println(io, "\n## Documented differences (reported, not asserted)\n")
    println(io, "| Reference | Estimator | Rows | Worst rel. error | Why |")
    println(io, "|---|---|---:|---:|---|")
    dd = Dict{Tuple{String,String,String},Vector{Row}}()
    dorder = Tuple{String,String,String}[]
    for r in filter(r -> isinf(r.tol), rows)
        k = (r.group, replace(r.estimator, r" (lo|hi)$" => ""), r.note)
        haskey(dd, k) || push!(dorder, k)
        push!(get!(dd, k, Row[]), r)
    end
    for k in dorder
        rs = dd[k]
        fin = filter(r -> isfinite(r.ref) && isfinite(r.got), rs)
        worst = isempty(fin) ? NaN : maximum(relerr, fin)
        wtxt = endswith(k[1], "α") ? join(unique("$(Int(r.ref)) vs $(Int(r.got))" for r in rs), ", ") : e(worst)
        ms = join(unique(r.m for r in rs)[1:min(end, 6)], ", ")
        println(io, "| $(k[1]) | $(k[2]) (m = $ms$(length(unique(r.m for r in rs)) > 6 ? ", …" : "")) | $(length(rs)) | $(wtxt) | $(k[3]) |")
    end
    print(io, NOTES)
    write(OUT, String(take!(io)))
    println("wrote ", OUT)
end

main()
