# report.jl — writes tools/validation/REPORT.md, the cross-check summary
# (agreement per reference × estimator, and every documented difference).
#
#   julia --project=. tools/validation/report.jl [out.md]
#
# Reads the same rows the test group asserts (test/validation/CrossCheck.jl).
using SigmaTau, Printf

include(joinpath(@__DIR__, "..", "..", "test", "validation", "CrossCheck.jl"))
using .CrossCheck: Row, relerr, passes, all_rows

const OUT = length(ARGS) >= 1 ? ARGS[1] : joinpath(@__DIR__, "REPORT.md")

const NOTES = """

## Conventions the rows encode

- **Bias corrections.** allantools reports every total estimator raw, so the
  allantools rows call `totdev`, `mtotdev`, `ttotdev` and `htotdev` with
  `correct_bias=false`. Stable32 bias-corrects TOTDEV and HTOTDEV and reports
  MTOT/TTOT raw; the Stable32 rows use SigmaTau's defaults for the former and
  `correct_bias=false` for the latter.
- **Thêo1 τ.** allantools reports Thêo1 at τ = m·τ0, SigmaTau and Stable32 at
  the effective τ = 0.75·m·τ0. Rows are matched on m.
- **Thêo1 bias.** Stable32's Thêo1 run is ThêoBR over the ladder SP1065
  prints, i = 0…⌊N/6 − 3⌋: the `theobr` rows, `correct_bias=:stable32`. Its
  runs with Alpha set to 0 are raw Thêo1: the `theo1` rows, `correct_bias=false`.
- **TOTDEV / MTOT EDF record length.** SP1065 Tables 7–8 give
  edf = b·T/τ − c. allantools uses T/τ = N/m, SigmaTau the span
  (N − 1)·τ0/τ, a 1/N relative difference; the EDF rows compare the formula
  at allantools' T.
- **TTOTDEV in allantools** is exactly MTOTDEV·τ/√3, so the generator derives
  it from the MTOT run instead of a second O(N·m) pass.
- **MTIE**: allantools' `mtie` (rolling window) is compared; Stable32's
  "MTIE (Fast)" agrees to 4e-5 on every τ it reports.
- **NBS 1000-point values.** MTOT/TTOT are Stable32 1.60's raw run; SP1065
  Table 31's 2.418528e-01 is Stable32 1.53's MTOT algorithm, which neither
  current program reproduces. The published HTOTDEV values carry the
  white-FM TotHvar bias (B = 0.995) above m = 1.

## Not covered

- Non-overlapped ADEV and HDEV (allantools `adev`/`hdev`, Stable32
  "Allan"/"Hadamard"): SigmaTau implements only the overlapped forms.
- MHDEV, HTDEV, MHTOTDEV, ThêoH, NCH: no reference implements them; they are
  tested against inlined kernels and identities in `test/stab/`.
"""

e(x) = isnan(x) ? "–" : x == 0 ? "0" : @sprintf("%.1e", x)

function main()
    rows = all_rows()
    io = IOBuffer()
    println(io, "# Reference cross-check report\n")
    println(io, "Generated by `tools/validation/report.jl` from the rows that ",
                "`test/validation/runtests.jl` asserts. Relative error is ",
                "|SigmaTau − reference| / |reference| (Welch spectra: relative to the spectral peak).\n")
    asserted = filter(r -> isfinite(r.tol), rows)
    println(io, "$(length(rows)) comparisons, $(length(asserted)) asserted, ",
                "$(count(!passes, rows)) failing.\n")

    println(io, "## Agreement\n")
    println(io, "| Reference | Estimator | Rows | Worst rel. error | Tolerance |")
    println(io, "|---|---|---:|---:|---:|")
    keyf(r) = (r.group, replace(r.estimator, r" (lo|hi)$" => ""))
    groups = Dict{Tuple{String,String},Vector{Row}}()
    order = Tuple{String,String}[]
    for r in asserted
        k = keyf(r)
        haskey(groups, k) || push!(order, k)
        push!(get!(groups, k, Row[]), r)
    end
    for k in order
        rs = groups[k]
        fin = filter(r -> isfinite(r.ref) && isfinite(r.got), rs)
        worst = isempty(fin) ? NaN : maximum(relerr, fin)
        println(io, "| $(k[1]) | $(k[2]) | $(length(rs)) | $(e(worst)) | $(e(maximum(r.tol for r in rs))) |")
    end

    println(io, "\n## Documented differences (reported, not asserted)\n")
    println(io, "| Reference | Estimator | Rows | Worst rel. error | Why |")
    println(io, "|---|---|---:|---:|---|")
    dd = Dict{Tuple{String,String,String},Vector{Row}}()
    dorder = Tuple{String,String,String}[]
    for r in filter(r -> isinf(r.tol), rows)
        k = (r.group, replace(r.estimator, r" (lo|hi)$" => ""), r.note)
        haskey(dd, k) || push!(dorder, k)
        push!(get!(dd, k, Row[]), r)
    end
    for k in dorder
        rs = dd[k]
        fin = filter(r -> isfinite(r.ref) && isfinite(r.got), rs)
        worst = isempty(fin) ? NaN : maximum(relerr, fin)
        wtxt = endswith(k[1], "α") ? join(unique("$(Int(r.ref)) vs $(Int(r.got))" for r in rs), ", ") : e(worst)
        ms = join(unique(r.m for r in rs)[1:min(end, 6)], ", ")
        println(io, "| $(k[1]) | $(k[2]) (m = $ms$(length(unique(r.m for r in rs)) > 6 ? ", …" : "")) | $(length(rs)) | $(wtxt) | $(k[3]) |")
    end
    print(io, NOTES)
    write(OUT, String(take!(io)))
    println("wrote ", OUT)
end

main()
